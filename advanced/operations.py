def add(number_1: float, number_2: float) -> float:
    """Returns the sum of two numbers."""
    calculated_adv_add = number_1 + number_2
    return calculated_adv_add


def subtract(number_1: float, number_2: float) -> float:
    """Returns the difference between two numbers."""
    calculated_sub = number_1 - number_2
    return calculated_sub


def multiply(number_1: float, number_2: float) -> float:
    """Returns the product of two numbers."""
    calculated_times = number_1 * number_2
    return calculated_times

def divide(number_1: float, number_2: float) -> float:
    """Returns the result of dividing the first number by the second."""
    calculated_divide = number_1 / number_2
    return calculated_divide